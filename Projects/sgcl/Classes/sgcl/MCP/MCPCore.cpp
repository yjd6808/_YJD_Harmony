#include "GameCoreHeader.h"
#include "MCPCore.h"

#include <sg/Core/AppConfig.h>

USING_NS_JC;
USING_NS_MCP;

//////////////////////////////////////////////////////////////////////////////////////////
MCPCore::MCPCore()
    : pMainMCP_(nullptr)
{
}

//////////////////////////////////////////////////////////////////////////////////////////
MCPCore::~MCPCore()
{
    MCPCore::Finalize();
}

//////////////////////////////////////////////////////////////////////////////////////////
bool MCPCore::Initialize()
{
    pMainMCP_ = MCPServer::Create();
    return pMainMCP_ != nullptr;
}

//////////////////////////////////////////////////////////////////////////////////////////
void MCPCore::Finalize()
{
    if (pMainMCP_)
    {
        pMainMCP_->Destroy();
        pMainMCP_ = nullptr;
    }
}

//////////////////////////////////////////////////////////////////////////////////////////
void MCPCore::PollEvents()
{
    if (pMainMCP_)
        pMainMCP_->PollEvents();
}

//////////////////////////////////////////////////////////////////////////////////////////
MCPServer& MCPCore::Main()
{
    jc_assert(pMainMCP_);
    return *pMainMCP_;
}
