//////////////////////////////////////////////////////////////////////////////////////////
// main
//////////////////////////////////////////////////////////////////////////////////////////
#include "Core.h"
#include "CenterCoreHeader.h"

#include <sg/LogSpecifier.h>

USING_NS_JC;
USING_NS_JNET;

int main()
{
    //////////////////////////////////////////////////////////////////////////////////////
    // 메인 리소스 초기화
    //////////////////////////////////////////////////////////////////////////////////////

    new char;

    Winsock::Initialize(2, 2);
    Console::SetSize(800, 400);
    InitializeJCore();
    InitializeNetLogger(LOG_SPECIFIER_CENTER);
    InitializeDefaultLogger(LOG_SPECIFIER_CENTER);
    InitializeCommonCore();
    InitializeServerCore();
    InitializeServerCenterLogo(true, 14);
    InitializeCenterCore();

    //////////////////////////////////////////////////////////////////////////////////////
    // 메인 루틴
    //////////////////////////////////////////////////////////////////////////////////////

    if (sg::NetGroup)
        sg::NetGroup->LaunchServer();

    if (sg::NetGroupMgr)
        sg::NetGroupMgr->ProcessMainUpdate();

    //////////////////////////////////////////////////////////////////////////////////////
    // 메인 리소스 정리
    //////////////////////////////////////////////////////////////////////////////////////

    FinalizeCenterCore();
    FinalizeServerCore();
    FinalizeCommonCore();
    FinalizeDefaultLogger();
    FinalizeNetLogger();
    FinalizeJCore();
    Winsock::Finalize();
    return Console::ReadKeyWhile("X키 입력시 종료", ConsoleKey::X) ? 0 : -1;
}
